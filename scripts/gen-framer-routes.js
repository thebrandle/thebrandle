'use strict';

/**
 * Static HTML for the Framer-served routes that are in the sitemap.
 *
 * Why this exists
 * ---------------
 * Those routes are served by the vercel.json catch-all, which hands every path
 * the same file. That file carries the HOMEPAGE title, the HOMEPAGE canonical
 * and no description at all. The `applyMeta` script already in the export fixes
 * all three once JavaScript runs, so the pages look correct in a browser.
 *
 * Google does not agree. Search Console has reported "Alternate page with
 * proper canonical tag" against pages in this sitemap repeatedly, most recently
 * on 2026-08-07. It reads the served canonical, sees a pointer to the homepage,
 * and declines to index. The client-side repair does not rescue them.
 *
 * So: write one file per route, byte-identical to the catch-all copy except for
 * the head. The page still renders exactly as it does today - same bundle, same
 * client-side router, same applyMeta - but a crawler now reads the right
 * canonical, title and description in the served bytes.
 *
 * Titles and descriptions are READ OUT OF `applyMeta`'s own ROUTES table rather
 * than restated here. A second copy would eventually disagree with the first,
 * and a served head that contradicts the rendered head is the exact failure this
 * file exists to remove.
 *
 *   node scripts/gen-framer-routes.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'thebrandle.framer.website', 'index.html');

/**
 * Routes that get a static file.
 *
 * Deliberately not "everything in ROUTES":
 *   '/'      is served by the real index.html, which keeps its hydrate
 *            attribute and must not be replaced by the de-hydrated copy.
 *   '/blog'  is generated by gen-opinly-blog.js and would be clobbered.
 *   the five legacy /projects/* slugs are not in the sitemap.
 */
const EMIT = [
  'about',
  'contact',
  'projects',
  'projects/dropx-website-design',
  'projects/orblead-website-design',
  'projects/shine-skincare-branding',
  'projects/oh-my-pasta-branding',
];

const attr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const text = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const src = fs.readFileSync(SRC, 'utf8');
const head = src.slice(0, src.indexOf('</head>'));

/** Lift applyMeta's ROUTES object out of the export by brace matching. */
function readRoutes() {
  const at = head.indexOf('var ROUTES = {');
  if (at === -1) throw new Error('applyMeta ROUTES table not found. The Framer export changed - re-check this script.');
  const start = head.indexOf('{', at);
  let depth = 0;
  for (let i = start; i < head.length; i++) {
    if (head[i] === '{') depth++;
    else if (head[i] === '}' && --depth === 0) {
      // eslint-disable-next-line no-eval -- our own build artefact, not user input
      return eval('(' + head.slice(start, i + 1) + ')');
    }
  }
  throw new Error('applyMeta ROUTES table is unbalanced.');
}

/**
 * Replace a tag that must appear exactly once in the head.
 * Counts with a global regex - String.match without /g returns a single match
 * object whatever the real count is, which makes a length check meaningless.
 */
function replaceOnce(html, re, replacement, label, route) {
  const counter = new RegExp(re.source, re.flags.includes('g') ? re.flags : re.flags + 'g');
  const headOnly = html.slice(0, html.indexOf('</head>'));
  const n = (headOnly.match(counter) || []).length;
  if (n !== 1) {
    throw new Error(`${route}: expected exactly one ${label} in the head, found ${n}. ` +
      'The Framer export changed shape - re-check scripts/gen-framer-routes.js before trusting its output.');
  }
  return html.replace(re, replacement);
}

const ROUTES = readRoutes();
let written = 0;

for (const dir of EMIT) {
  const key = '/' + dir;
  const meta = ROUTES[key];
  if (!meta) throw new Error(`${key} is not in applyMeta's ROUTES table, so there is no title or description to serve.`);
  if (!meta.title || !meta.description || !meta.canonical) throw new Error(`${key} is missing title, description or canonical.`);

  let html = src;
  html = replaceOnce(html, /<title>[\s\S]*?<\/title>/, `<title>${text(meta.title)}</title>`, '<title>', key);
  html = replaceOnce(html, /<link rel="canonical" href="[^"]*"\s*\/?>/,
    `<link rel="canonical" href="${attr(meta.canonical)}"/>`, 'canonical link', key);
  html = replaceOnce(html, /<meta property="og:url" content="[^"]*"\s*\/?>/,
    `<meta property="og:url" content="${attr(meta.canonical)}"/>`, 'og:url', key);

  // The export ships no description at all, so this is an insert, not a replace.
  html = html.replace(/<\/title>/,
    '</title>' +
    `\n<meta name="description" content="${attr(meta.description)}"/>` +
    `\n<meta property="og:title" content="${attr(meta.title)}"/>` +
    `\n<meta property="og:description" content="${attr(meta.description)}"/>` +
    `\n<meta name="twitter:title" content="${attr(meta.title)}"/>` +
    `\n<meta name="twitter:description" content="${attr(meta.description)}"/>`);

  const outDir = path.join(ROOT, dir);
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, 'index.html'), html);
  written++;
  console.log(`  ${dir}/index.html  ${(html.length / 1048576).toFixed(2)}MB  ${meta.canonical}`);
}

console.log(`framer-routes: wrote ${written} pages, meta taken from applyMeta's own ROUTES table`);
